class UnusedRemoteService implements RemoteService {
  @override
  dynamic noSuchMethod(Invocation invocation) => super.noSuchMethod(invocation);
}

const boundary = 'media-test-boundary';
List<int> multipart(List<(String, List<int>)> files) => [
  for (final (name, bytes) in files) ...[
    ...utf8.encode(
      '--$boundary\r\n'
      'Content-Disposition: form-data; name="file"; filename="$name"\r\n\r\n',
    ),
    ...bytes,
    ...utf8.encode('\r\n'),
  ],
  ...utf8.encode('--$boundary--\r\n'),
];

Request request(String code, Object body, {int? contentLength}) => Request(
  'POST',
  Uri.parse('http://localhost/upload/$code/'),
  headers: {
    'content-type': 'multipart/form-data; boundary=$boundary',
    if (contentLength != null) 'content-length': '$contentLength',
  },
  body: body is List<int> ? Stream<List<int>>.value(body) : body,
);

class ControlledWriter implements UploadFileWriter {
  final RandomAccessFile file;
  final Completer<void> reachedClose;
  final Future<void> releaseClose;
  ControlledWriter(this.file, this.reachedClose, this.releaseClose);
  @override
  Future<void> write(List<int> bytes) async {
    await file.writeFrom(bytes);
  }

  @override
  Future<void> flush() async {
    await file.flush();
  }

  @override
  Future<void> close() async {
    reachedClose.complete();
    await releaseClose;
    await file.close();
  }
}

void main() {
  late Directory directory;
  late WebService service;
  final services = <WebService>[];
  Future<Response> handle(Request request) async =>
      await service.handler(request);

  WebService create({StreamingUploadReceiver? receiver, int slots = 2}) {
    final config = AppConfig.fromJson({});
    final instance = WebService(
      config,
      config.webServer,
      UnusedRemoteService(),
      cacheDirectory: directory,
      uploadReceiver: receiver,
      maxConcurrentUploads: slots,
      startServer: false,
    );
    services.add(instance);
    return instance;
  }

  setUp(() async {
    directory = await Directory.systemTemp.createTemp('media-upload-');
    service = create();
  });
  tearDown(() async {
    for (final instance in services) {
      await instance.close();
    }
    services.clear();
    await directory.delete(recursive: true);
  });

  test(
    'multiple files stay separate, preserve subfolders and support no length',
    () async {
      final body = multipart([
        ('one.jpg', [1, 2, 3]),
        ('album/two.mp4', [4, 5]),
      ]);
      final upload = request(service.code, body);
      expect(upload.contentLength, isNull);
      final response = await handle(upload);
      expect(response.statusCode, 200);
      expect(await File('${directory.path}/one.jpg').readAsBytes(), [1, 2, 3]);
      expect(await File('${directory.path}/album/two.mp4').readAsBytes(), [
        4,
        5,
      ]);
      final files = await directory.list(recursive: true).toList();
      expect(files.where((file) => file.path.endsWith('.part')), isEmpty);
    },
  );

  test(
    'accepts multipart generated by the existing HTTP client library',
    () async {
      final errors = <Object>[];
      final logs = Logger.root.onRecord.listen((record) {
        if (record.error case final error?) errors.add(error);
      });
      addTearDown(logs.cancel);
      final uri = Uri.parse('http://localhost/upload/${service.code}/');
      final envelope = http.MultipartRequest('POST', uri);
      final bytes = List<int>.generate(256, (index) => index);
      envelope.files.add(
        http.MultipartFile.fromBytes(
          'file',
          bytes,
          filename: 'album/summer 01.jpg',
        ),
      );
      final body = envelope.finalize();
      final response = await handle(
        Request('POST', uri, headers: envelope.headers, body: body),
      );
      expect(response.statusCode, 200, reason: errors.join('\n'));
      expect(
        await File('${directory.path}/album/summer 01.jpg').readAsBytes(),
        bytes,
      );
    },
  );

  test('response and replacement wait for file close', () async {
    final reachedClose = Completer<void>();
    final releaseClose = Completer<void>();
    addTearDown(() {
      if (!releaseClose.isCompleted) releaseClose.complete();
    });
    service = create(
      receiver: StreamingUploadReceiver(
        writerFactory: (file) async {
          return ControlledWriter(
            await file.open(mode: FileMode.write),
            reachedClose,
            releaseClose.future,
          );
        },
      ),
    );
    final destination = File('${directory.path}/same.jpg');
    await destination.writeAsBytes([9]);
    var responded = false;
    final response = handle(
      request(
        service.code,
        multipart([
          ('same.jpg', [1, 2]),
        ]),
      ),
    );
    unawaited(
      response.then((_) {
        responded = true;
      }),
    );
    await reachedClose.future;
    expect(responded, isFalse);
    expect(await destination.readAsBytes(), [9]);
    releaseClose.complete();
    expect((await response).statusCode, 200);
    expect(await destination.readAsBytes(), [1, 2]);
  });

  test('bad code rejects without consuming the request', () async {
    var listened = false;
    final body = StreamController<List<int>>(
      onListen: () {
        listened = true;
      },
    );
    expect((await handle(request('wrong', body.stream))).statusCode, 403);
    expect(listened, isFalse);
    unawaited(body.close());
  });

  test('missing files and malformed requests return errors', () async {
    expect(
      (await handle(
        Request(
          'POST',
          Uri.parse('http://localhost/upload/${service.code}/'),
          body: 'bad',
        ),
      )).statusCode,
      400,
    );
    expect(
      (await handle(request(service.code, multipart([])))).statusCode,
      400,
    );
  });

  test(
    'actual bytes are limited even with a misleading small content length',
    () async {
      service = create(
        receiver: StreamingUploadReceiver(
          limits: const UploadLimits(maxBytes: 180),
        ),
      );
      final body = multipart([('one.jpg', List.filled(200, 1))]);
      final response = await handle(
        request(service.code, body, contentLength: 1),
      );
      expect(response.statusCode, 413);
      expect(await directory.list(recursive: true).toList(), isEmpty);
    },
  );

  test(
    'stream error removes staged files and permits another request',
    () async {
      final bytes = multipart([
        ('one.jpg', [1, 2]),
        ('two.jpg', [3]),
      ]);
      Stream<List<int>> broken() async* {
        yield bytes.sublist(0, bytes.length - 10);
        throw const FileSystemException('broken stream');
      }

      final response = await handle(request(service.code, broken()));
      expect(response.statusCode, 500, reason: await response.readAsString());
      expect(await directory.list(recursive: true).toList(), isEmpty);
      expect(
        (await handle(
          request(
            service.code,
            multipart([
              ('ok.jpg', [7]),
            ]),
          ),
        )).statusCode,
        200,
      );
    },
  );

  test(
    'duplicate destinations reject the batch and preserve previous files',
    () async {
      final destination = File('${directory.path}/same.jpg');
      await destination.writeAsBytes([9]);
      final response = await handle(
        request(
          service.code,
          multipart([
            ('same.jpg', [1]),
            ('same.jpg', [2]),
          ]),
        ),
      );
      expect(response.statusCode, 409);
      expect(await destination.readAsBytes(), [9]);
      expect(await directory.list().length, 1);
    },
  );

  test('slots are reserved before reading and closed service cancels stalled input', () async {
    service = create(slots: 1);
    final input = StreamController<List<int>>();
    final pending = handle(request(service.code, input.stream));
    final rejected = await handle(
      request(
        service.code,
        multipart([
          ('two.jpg', [2]),
        ]),
      ),
    );
    expect(rejected.statusCode, 429);
    expect(rejected.headers['retry-after'], isNotNull);
    await service.close();
    expect((await pending).statusCode, isNot(200));
    expect(await directory.list(recursive: true).toList(), isEmpty);
    unawaited(input.close());
    expect(
      (await handle(
        request(
          service.code,
          multipart([
            ('late.jpg', [1]),
          ]),
        ),
      )).statusCode,
      503,
    );
  });

  test(
    'concurrent same destination is a conflict without corrupting first upload',
    () async {
      final reachedClose = Completer<void>();
      final releaseClose = Completer<void>();
      addTearDown(() {
        if (!releaseClose.isCompleted) releaseClose.complete();
      });
      service = create(
        receiver: StreamingUploadReceiver(
          writerFactory: (file) async {
            return ControlledWriter(
              await file.open(mode: FileMode.write),
              reachedClose,
              releaseClose.future,
            );
          },
        ),
      );
      final first = handle(
        request(
          service.code,
          multipart([
            ('same.jpg', [1]),
          ]),
        ),
      );
      await reachedClose.future;
      final second = await handle(
        request(
          service.code,
          multipart([
            ('same.jpg', [2]),
          ]),
        ),
      );
      expect(second.statusCode, 409);
      releaseClose.complete();
      expect((await first).statusCode, 200);
      expect(await File('${directory.path}/same.jpg').readAsBytes(), [1]);
    },
  );

  test(
    'partial publish reports committed names and cleans unpublished parts',
    () async {
      final secondClose = Completer<void>();
      final release = Completer<void>();
      addTearDown(() {
        if (!release.isCompleted) release.complete();
      });
      var opened = 0;
      service = create(
        receiver: StreamingUploadReceiver(
          writerFactory: (file) async {
            final second = ++opened == 2;
            return ControlledWriter(
              await file.open(mode: FileMode.write),
              second ? secondClose : Completer<void>(),
              second ? release.future : Future<void>.value(),
            );
          },
        ),
      );
      final pending = handle(
        request(
          service.code,
          multipart([
            ('first.jpg', [1]),
            ('blocked.jpg', [2]),
          ]),
        ),
      );
      await secondClose.future;
      await Directory('${directory.path}/blocked.jpg').create();
      release.complete();
      final response = await pending;
      expect(response.statusCode, 500);
      expect(json.decode(await response.readAsString()), {
        'error': 'Could not store upload',
        'published': ['first.jpg'],
      });
      expect(await File('${directory.path}/first.jpg').readAsBytes(), [1]);
      expect(
        await directory
            .list(recursive: true)
            .any((file) => file.path.endsWith('.part')),
        isFalse,
      );
    },
  );

  test('rapid enable/disable/enable closes every listener', () async {
    final probe = await ServerSocket.bind(InternetAddress.loopbackIPv4, 0);
    final port = probe.port;
    await probe.close();
    final config = AppConfig.fromJson({
      'web': {'port': port, 'alwaysEnabled': false},
    });
    service = WebService(
      config,
      config.webServer,
      UnusedRemoteService(),
      cacheDirectory: directory,
      startServer: false,
    );
    services.add(service);
    service.enabled = true;
    await Future<void>.delayed(Duration.zero);
    service.enabled = false;
    service.enabled = true;
    await service.close();
    final available = await ServerSocket.bind(InternetAddress.anyIPv4, port);
    await available.close();
  });

  test('TCP disconnect cleans partial data and releases upload slot', () async {
    service = create(
      slots: 1,
      receiver: StreamingUploadReceiver(
        limits: const UploadLimits(idleTimeout: Duration(seconds: 1)),
      ),
    );
    final server = await shelf_io.serve(
      service.handler,
      InternetAddress.loopbackIPv4,
      0,
    );
    final socket = await Socket.connect(
      InternetAddress.loopbackIPv4,
      server.port,
    );
    addTearDown(socket.destroy);
    addTearDown(() => server.close(force: true));
    final partial = utf8.encode(
      '--$boundary\r\nContent-Disposition: form-data; name="file"; filename="broken.jpg"\r\n\r\nbytes',
    );
    socket.add(
      utf8.encode(
        'POST /upload/${service.code}/ HTTP/1.1\r\nHost: localhost\r\nContent-Type: multipart/form-data; boundary=$boundary\r\nContent-Length: 100000\r\n\r\n',
      ),
    );
    socket.add(partial);
    await socket.flush();
    // Observe that the real HTTP handler has opened staging before disconnect.
    final startedDeadline = DateTime.now().add(const Duration(seconds: 3));
    while (!(await directory
        .list(recursive: true)
        .any((file) => file.path.endsWith('.part')))) {
      if (DateTime.now().isAfter(startedDeadline))
        fail('HTTP upload never opened staging');
      await Future<void>.delayed(const Duration(milliseconds: 10));
    }
    expect(
      (await handle(
        request(
          service.code,
          multipart([
            ('busy.jpg', [1]),
          ]),
        ),
      )).statusCode,
      429,
    );
    socket.destroy();

    final client = HttpClient();
    addTearDown(() => client.close(force: true));
    final until = DateTime.now().add(const Duration(seconds: 3));
    int status;
    do {
      final next = await client.postUrl(
        Uri.parse('http://127.0.0.1:${server.port}/upload/${service.code}/'),
      );
      next.headers.contentType = ContentType(
        'multipart',
        'form-data',
        parameters: {'boundary': boundary},
      );
      next.add(
        multipart([
          ('after.jpg', [8]),
        ]),
      );
      final response = await next.close();
      status = response.statusCode;
      await response.drain<void>();
      if (status != 429) break;
      await Future<void>.delayed(const Duration(milliseconds: 20));
    } while (DateTime.now().isBefore(until));
    expect(status, 200);
    expect(await File('${directory.path}/after.jpg').readAsBytes(), [8]);
    expect(File('${directory.path}/broken.jpg').existsSync(), isFalse);
    expect(
      await directory
          .list(recursive: true)
          .any((file) => file.path.endsWith('.part')),
      isFalse,
    );
  });
}
