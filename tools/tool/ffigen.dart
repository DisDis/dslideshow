import 'dart:io';

import 'package:ffigen/ffigen.dart';

Future<void> main() async {
  final root = Platform.script.resolve('../');
  await FfiGenerator(
    input: Input(entryPoints: [root.resolve('third_party/posix_clock.h')]),
    visitors: [
      Visitor(
        func: (node) {
          node.isIncluded = {'clock_gettime', 'getrusage'}.contains(node.originalName);
          node.recordUse = node.isIncluded;
        },
        struct: (node) {
          node.isIncluded = {'timespec', 'rusage', 'timeval'}.contains(node.originalName);
        },
        field: (node) {
          if (node.originalName.startsWith('__ru_')) {
            node.name = 'reserved${node.originalName.substring(2)}';
          }
        },
      ),
    ],
    output: Output(
      dart: DartOutput(path: root.resolve('lib/src/third_party/posix_clock.g.dart')),
      style: const NativeExternalBindings(),
      recordUseMapping: root.resolve('lib/src/third_party/posix_clock.record_use_mapping.g.dart'),
      preamble: '''// Generated by package:ffigen. Do not edit manually.
// Regenerate with dart run tool/ffigen.dart on Linux (LP64 x64/arm64).
// Bindings to GNU C Library time.h and sys/resource.h; LGPL-2.1-or-later.
// time.h: Copyright (C) 1991-2026 Free Software Foundation, Inc.
// sys/resource.h: Copyright (C) 1992-2026 Free Software Foundation, Inc.
// ignore_for_file: type=lint, experimental_member_use
''',
    ),
  ).generate();
}
